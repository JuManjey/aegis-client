package com.aegis.network.tor

import com.aegis.core.common.security.TorMode
import kotlinx.coroutines.flow.StateFlow

/**
 * Абстракция транспортного слоя через встроенный Tor (§7.2, §10.5, §10.11).
 *
 * Реализация ФАЗЫ 5 будет обёрткой над Arti (Rust) через JNI/UniFFI и поднимет
 * локальный SOCKS-прокси, через который пойдёт весь клиентский трафик. Сервер-
 * релей публикуется как Onion Service v3.
 *
 * На ФАЗЕ 1 без фичи `tor` используется [FakeTorTransport]: статус
 * [TorStatus.Unavailable], без фейкового «подключено» и без SOCKS-порта.
 */
interface TorTransport {

    /** Текущий статус транспорта (для UI-индикатора). */
    val status: StateFlow<TorStatus>

    /** Порт локального SOCKS5-прокси, когда [status] == Connected, иначе null. */
    val socksPort: Int?

    /**
     * Применить режим сети (§8: `net.tor`): [TorMode.ALWAYS] поднимает Tor,
     * [TorMode.OFF] останавливает его полностью. E2EE-шифрование от этого НЕ
     * зависит. Вызывает только контроллер режима сети приложения — в нужном
     * порядке относительно закрытия прямых соединений.
     *
     * Идемпотентно: если клиент уже поднят с тем же конфигом, ничего не делает.
     */
    suspend fun applyMode(mode: TorMode)

    /**
     * ПРИНУДИТЕЛЬНО перезапустить клиент Tor, даже если конфиг не менялся.
     *
     * Нужен сторожу ([TorTransport] сам за собой не следит): встроенный Arti
     * держит цепи поверх TCP-соединений, привязанных к интерфейсу, который был
     * активен на момент их построения. После смены сети (Wi-Fi ⇄ мобильный, VPN
     * вверх/вниз) или после долгого сна процесса эти соединения мертвы, но с
     * точки зрения самого клиента всё «connected»: он узнает об этом только
     * когда очередной запрос упрётся в таймаут. Пересоздание клиента —
     * единственный надёжный способ вернуть трафик за секунды, а не за минуты.
     *
     * @param reason короткая машинная причина для журнала (`сеть`, `статус`,
     *   `релей`, `сон`) — по ней в диагностике видно, кто дёрнул перезапуск.
     */
    suspend fun restart(reason: String)

    /** Остановить транспорт и освободить ресурсы. */
    suspend fun shutdown()

    /**
     * Монотонное время ([android.os.SystemClock.elapsedRealtime]) последней
     * СМЕНЫ статуса bootstrap, либо 0, если транспорт не запускался.
     *
     * Сторожу нужен именно момент последнего продвижения, а не сам статус:
     * «Bootstrapping 40 %» полчаса подряд — это отказ, который по статусу не
     * отличить от нормального старта.
     */
    val statusChangedAtElapsed: Long
}
