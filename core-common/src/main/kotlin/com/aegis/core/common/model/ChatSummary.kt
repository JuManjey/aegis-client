package com.aegis.core.common.model

/**
 * Краткая карточка чата для главного экрана (§13: список активных чатов).
 *
 * На ФАЗЕ 1 это доменная модель-контракт; источником данных позже станет
 * зашифрованное хранилище (data-storage). Никаких plaintext-полей, которые
 * могли бы утечь в логи, тут быть не должно (модель держим минимальной).
 */
data class ChatSummary(
    val id: String,
    /** Отображаемое имя: локальный алиас чата или публичный никнейм контакта. */
    val displayName: String,
    /**
     * Публичный никнейм обмена (идентичность). Нужен диалогу переименования,
     * чтобы показать, к чему вернётся чат при пустом поле.
     */
    val nickname: String = "",
    /** Превью последнего сообщения (уже расшифрованное для показа в UI). */
    val lastMessagePreview: String,
    /** Человекочитаемая метка времени последнего сообщения. */
    val timestampLabel: String,
    /** Количество непрочитанных сообщений. */
    val unreadCount: Int = 0,
    /** Верифицирован ли отпечаток контакта (safety number, §6.2). */
    val verified: Boolean = false,
    /** Активна ли E2EE-сессия для этого чата. */
    val e2eeActive: Boolean = true,
    /** В чёрном списке (§14.2). */
    val blocked: Boolean = false,
    /** Уведомления от контакта заглушены прямо сейчас (§14.5). */
    val muted: Boolean = false,
)
