package com.aegis.core.common.contact

import kotlinx.serialization.json.Json

/**
 * Каноничная сериализация ПОДПИСЫВАЕМЫХ нагрузок (`docs/contact_requests.md`).
 *
 * ЗАЧЕМ ОТДЕЛЬНЫЙ ОБЪЕКТ. Подпись считается над байтами JSON, поэтому
 * подписывающая и проверяющая сторона обязаны получить их ПОБАЙТОВО
 * одинаковыми. Если конфигурацию `Json` передавать параметром (как было
 * сначала), достаточно одного расхождения — например `encodeDefaults = true` у
 * публикатора и `false` у проверяющего — и подпись перестаёт сходиться: поля,
 * равные значениям по умолчанию (`v`, пустые строки), у одной стороны попадают
 * в байты, а у другой пропускаются. Диагностируется это как `BadSignature`, то
 * есть как «возможна подмена ключей», хотя данные подлинные.
 *
 * Поэтому конфигурация зафиксирована здесь и НЕ параметризуется:
 *
 *  * `encodeDefaults = true` — поля со значениями по умолчанию всегда в байтах;
 *  * порядок полей — порядок объявления в `data class` (детерминирован
 *    kotlinx.serialization), поэтому дополнительной сортировки не требуется;
 *  * `ignoreUnknownKeys` здесь НЕ нужен: он влияет только на разбор, а этот
 *    экземпляр используется исключительно для кодирования.
 *
 * Разбор входящих нагрузок идёт отдельным «терпимым» экземпляром `Json`
 * (`ignoreUnknownKeys = true`), чтобы новые поля не ломали старые сборки.
 */
internal val CanonicalJson: Json = Json {
    encodeDefaults = true
    prettyPrint = false
}
