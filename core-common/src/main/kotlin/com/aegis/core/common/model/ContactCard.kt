package com.aegis.core.common.model

import com.aegis.core.common.contact.ContactTrust

/**
 * Карточка уже добавленного контакта для раздела «Контакты» (§14.1): список,
 * поиск и экран подробностей.
 *
 * Отдельная модель, а не `StoredContact` из хранилища: та несёт параметры
 * E2EE-сессии (identity, prekey-бандл, состояние ratchet). UI они не нужны, а
 * протаскивать их до composable значит тащить ключевой материал в слой, который
 * рендерит скриншоты и превью. Здесь только то, что показывается человеку.
 *
 * Как и [ChatSummary], модель плоская и производная: источник истины — SQLCipher,
 * карточки пересобираются при каждом обновлении списка.
 */
data class ContactCard(
    /** `accountId` контакта — он же ключ во всех хранилищах. */
    val id: String,
    /** Имя для показа: локальный алиас, иначе публичный никнейм, иначе id. */
    val displayName: String,
    /** Публичный никнейм обмена (идентичность собеседника). */
    val nickname: String = "",
    /** Локальное имя на этом устройстве; пусто — показывается [nickname]. */
    val localName: String = "",
    /** Отпечаток identity-ключа (safety number) для ручной сверки, §6.2. */
    val fingerprint: String = "",
    /** Отпечаток сверен вручную (§14.3). */
    val verified: Boolean = false,
    /** В чёрном списке (§14.2). */
    val blocked: Boolean = false,
    /** Уведомления от контакта заглушены прямо сейчас (§14.5). */
    val muted: Boolean = false,
    /** Как контакт попал на устройство: личный обмен или удалённое добавление. */
    val trust: ContactTrust = ContactTrust.UNKNOWN,
    /** Ключи слоя B получены — сессия устанавливается/установлена (§6.1). */
    val e2eeActive: Boolean = false,
    /** Сколько устройств контакта известно (мультидевайс, §7.1.1). */
    val deviceCount: Int = 1,
) {
    /**
     * Нормализованный «стог сена» для текстового поиска: все имена в одной
     * строке нижним регистром.
     *
     * Считается один раз при сборке карточки, а не на каждое нажатие клавиши:
     * фильтр прогоняется по всему списку при КАЖДОМ изменении запроса, и
     * нормализация внутри предиката давала бы O(контакты × символы) аллокаций
     * на каждый символ ввода. Карточки же пересобираются только при изменении
     * данных.
     */
    private val nameHaystack: String =
        "$displayName\u0000$nickname\u0000$localName".lowercase()

    /**
     * Отдельный «стог сена» для кодов: accountId и отпечаток без разделителей.
     *
     * Пользователь ищет по тому, что видит, а видит он их сгруппированными
     * (`AB12 CD34 …`) и в верхнем регистре. Сравнивать это с тем, что лежит в
     * БД, можно только сняв регистр и разделители с ОБЕИХ сторон — иначе
     * скопированный с экрана отпечаток никогда не найдётся.
     */
    private val codeHaystack: String =
        "$id\u0000$fingerprint".lowercase().filter { it.isLetterOrDigit() || it == '\u0000' }

    /**
     * Подходит ли контакт под поисковый запрос. Пустой запрос подходит всем.
     *
     * Имена ищутся подстрокой как есть, коды (accountId, отпечаток) — по
     * нормализованной форме, поэтому работает и вставка `AB12 CD34`, и ввод
     * `ab12cd34`, и кусок из середины.
     */
    fun matches(query: String): Boolean {
        val needle = query.trim().lowercase()
        if (needle.isEmpty()) return true
        if (nameHaystack.contains(needle)) return true
        val code = needle.filter { it.isLetterOrDigit() }
        return code.isNotEmpty() && codeHaystack.contains(code)
    }
}
