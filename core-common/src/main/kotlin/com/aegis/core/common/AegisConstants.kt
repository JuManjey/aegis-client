package com.aegis.core.common

/**
 * Глобальные инвариантные константы продукта AEGIS.
 *
 * Значения здесь — это ЖЁСТКИЕ правила из технического задания (§7.3), которые
 * нельзя нарушать ни в UI, ни в бизнес-логике. Держим их в одном месте,
 * чтобы исключить рассинхронизацию между модулями.
 */
object AegisConstants {

    /**
     * Жёсткий верхний предел срока хранения переписки (§7.3):
     * сообщения старше 7 дней не хранятся вообще — ни локально, ни на сервере.
     * Превысить это значение нельзя ни через настройки, ни через пресеты.
     */
    const val AUTO_DELETE_MAX_DAYS: Int = 7

    /** Минимально допустимый срок хранения (можно указывать меньше 7, но не меньше 1). */
    const val AUTO_DELETE_MIN_DAYS: Int = 1

    /** Значение по умолчанию — максимально допустимое (§8, все пресеты = 7). */
    const val AUTO_DELETE_DEFAULT_DAYS: Int = AUTO_DELETE_MAX_DAYS

    /**
     * Автоблокировка приложения по таймауту бездействия (§14.3).
     * Значение — число минут; [AUTO_LOCK_OFF] (0) отключает таймер (блокировка
     * тогда только ручная/по duress). Верхний предел ограничивает разумным
     * диапазоном, чтобы «бездействие» не растягивалось на часы.
     */
    const val AUTO_LOCK_OFF: Int = 0

    /** Максимально допустимый таймаут автоблокировки в минутах. */
    const val AUTO_LOCK_MAX_MINUTES: Int = 60

    /** Значение по умолчанию — «Параноик»: короткий таймаут (§8). */
    const val AUTO_LOCK_DEFAULT_MINUTES: Int = 1

    /**
     * Максимальный размер ИСХОДНОГО (расшифрованного) вложения в байтах (§14.4).
     * Реалтайм-транспорт идёт через Tor (медленно/дорого) и вложение проходит
     * каскад слоя A через JNI (base64) — поэтому в v1 держим разумный потолок.
     * Больше нельзя (UI не даст выбрать/отправить).
     */
    const val ATTACHMENT_MAX_BYTES: Long = 8L * 1024 * 1024

    /**
     * Максимальный размер вложения, скачиваемого АВТОМАТИЧЕСКИ (§14.4), когда
     * автозагрузка включена. Крупнее — только по явному тапу пользователя (чтобы
     * не гонять большие объёмы через Tor без спроса).
     */
    const val ATTACHMENT_AUTO_DOWNLOAD_MAX_BYTES: Long = 2L * 1024 * 1024

    // --- Голосовые сообщения (§14.4) ----------------------------------------

    /**
     * Частота дискретизации записи голоса (Гц). 16 кГц — стандарт wideband-речи:
     * разборчивость та же, что у 44.1 кГц, а данных втрое меньше, что для
     * транспорта через Tor решающе.
     */
    const val VOICE_SAMPLE_RATE_HZ: Int = 16_000

    /**
     * Целевой битрейт AAC-LC (бит/с). 24 кбит/с на моно-речи в 16 кГц ≈ 3 КБ/с,
     * то есть минута голосового ≈ 180 КБ. Это на порядок ниже потолка вложения
     * ([ATTACHMENT_MAX_BYTES]) и проходит через Tor за единицы секунд.
     */
    const val VOICE_BITRATE_BPS: Int = 24_000

    /**
     * Максимальная длительность одного голосового (мс). При достижении запись
     * останавливается САМА и уходит как готовое сообщение — это надёжнее, чем
     * оборвать её с потерей: 5 минут при [VOICE_BITRATE_BPS] ≈ 0.9 МБ, то есть
     * заведомо внутри [ATTACHMENT_MAX_BYTES] и лимита блоба на релее.
     */
    const val VOICE_MAX_DURATION_MS: Long = 5L * 60 * 1000

    /**
     * Минимальная длительность (мс). Короче — это промах по кнопке, а не
     * сообщение: отправлять такое означало бы спамить собеседника щелчками.
     */
    const val VOICE_MIN_DURATION_MS: Long = 700L

    /**
     * Шаг измерения громкости для огибающей (мс). 50 мс = 20 измерений в
     * секунду: достаточно, чтобы поймать слоги, и достаточно редко, чтобы
     * пересэмплирование в [com.aegis.core.common.audio.VoiceWaveform.BUCKETS]
     * не теряло всплески даже на самой короткой записи.
     */
    const val VOICE_WAVEFORM_STEP_MS: Int = 50

    /** MIME-тип записанного голосового (AAC-LC в контейнере ADTS). */
    const val VOICE_MIME_TYPE: String = "audio/aac"

    /** Имя продукта (единая точка правды для UI и телеметрии без чувствительных данных). */
    const val APP_NAME: String = "AEGIS"
}
