package com.aegis.core.common.contact

import kotlinx.serialization.Serializable

/**
 * Запись каталога обнаружения — то, что владелец адреса публикует на релее,
 * чтобы его могли добавить удалённо (`docs/contact_requests.md`, PROTOCOL.md §4.7).
 *
 * На релей запись уходит ЗАПЕЧАТАННОЙ (XChaCha20-Poly1305 на ключе, выведенном
 * из тега обнаружения; AAD привязан к индексу). Сервер не может её прочитать и
 * не знает, чья она — он видит опаковый индекс и шифртекст.
 *
 * ВНУТРИ — только ПУБЛИЧНЫЕ ключи. Приватного материала здесь нет и быть не
 * может: запись по замыслу доступна каждому, кому владелец дал свой адрес.
 *
 * ПРОВЕРКА ПОЛУЧАТЕЛЕМ (fail-closed, все пункты обязательны, см.
 * `DirectoryRecordVerifier`):
 *  1. AEAD открылся под ключом из тега → публикатор знал тег;
 *  2. [sigB64] верна под [ed25519Hex];
 *  3. `account_id_from(ed25519) == accountId` — **привязка accountId к ключу**;
 *  4. [accountId] совпал с полученным вне сети адресом;
 *  5. [tagCommitB64] совпал с `SHA-256(label || tag)` — запись для ЭТОГО тега;
 *  6. [expiresAtMs] в будущем, [issuedAtMs] не откатился относительно кэша.
 *
 * Подпись считается над каноничными байтами [canonicalBytes] — тем же JSON без
 * поля `sigB64`. Конфигурация сериализации зафиксирована в [CanonicalJson] и НЕ
 * параметризуется: подписывающий и проверяющий обязаны получить побайтово
 * одинаковый результат. Ранее `Json` передавался параметром, стороны разошлись
 * по `encodeDefaults`, и подлинные записи отвергались как `BadSignature`.
 */
@Serializable
data class DirectoryRecord(
    val v: Int = VERSION,
    /** `aegis:<32 hex>` — коммитмент к [ed25519Hex]. */
    val accountId: String,
    /** Публичный Ed25519-ключ аккаунта (64 hex) — им подписана запись. */
    val ed25519Hex: String,
    /** Публичный X25519-ключ аккаунта (64 hex) — статический DH рукопожатия. */
    val x25519Hex: String,
    /** Отпечаток аккаунта (safety number) для сверки в UI. */
    val fingerprint: String = "",
    /** Ник для показа. НЕ является идентификатором и ничего не аутентифицирует. */
    val nickname: String = "",
    /** Публичные ключи слоя B по устройствам владельца (мультидевайс §5). */
    val devices: List<DirectoryDevice> = emptyList(),
    /** `SHA-256(label || tag)` в base64 — доказывает, что запись для этого тега. */
    val tagCommitB64: String = "",
    val issuedAtMs: Long = 0L,
    val expiresAtMs: Long = 0L,
    /** Ed25519-подпись над [canonicalBytes] (base64). Вне подписываемых байт. */
    val sigB64: String = "",
) {
    /**
     * Каноничные байты для подписи/проверки: та же запись с пустой [sigB64].
     *
     * Конфигурация сериализации НЕ параметризуется намеренно (см. [CanonicalJson]):
     * подписывающий и проверяющий обязаны получить побайтово одинаковый результат,
     * а параметр позволял им разойтись и давал ложный `BadSignature` на подлинных
     * данных.
     */
    fun canonicalBytes(): ByteArray =
        CanonicalJson.encodeToString(serializer(), copy(sigB64 = "")).toByteArray(Charsets.UTF_8)

    companion object {
        const val VERSION: Int = 1

        /** Разумный потолок числа устройств в записи (защита от раздувания). */
        const val MAX_DEVICES: Int = 16
    }
}

/** Публичные ключи слоя B одного устройства владельца записи. */
@Serializable
data class DirectoryDevice(
    /** device id владельца (1..255). */
    val deviceId: Int,
    /** Публичный Signal identity-ключ устройства (base64). */
    val signalIdentityB64: String,
    /** Публичный prekey-бандл устройства для X3DH/PQXDH (JSON-строка). */
    val bundleJson: String,
)

/**
 * Заявка на ПУБЛИЧНЫЙ алиас (`@ник`) — PROTOCOL.md §4.8.
 *
 * В отличие от [DirectoryRecord], заявка НЕ запечатана: публичный ник должен
 * читаться каждым, кто его угадал. Поэтому внутри нет ничего, кроме указателя:
 * accountId, ключ подписи и адрес приватной записи каталога. Ни prekey-бандлов,
 * ни списка устройств здесь нет — их отдаёт только приватный каталог.
 *
 * Релей проверяет подпись и привязку `accountId ↔ ed25519` (иначе алиас
 * угонялся бы перезаписью), но клиент ОБЯЗАН перепроверить всё сам — заявка
 * самодостаточна, и доверять ответу сервера не требуется.
 */
@Serializable
data class AliasClaim(
    val v: Int = VERSION,
    /** Индекс алиаса (url-safe base64) — тот же, что в пути запроса. */
    val aliasIndex: String,
    val accountId: String,
    val ed25519Hex: String,
    /** Индекс приватной записи каталога владельца (url-safe base64). */
    val discoveryIndex: String,
    /**
     * Тег обнаружения, который владелец согласен раскрыть ПУБЛИЧНО.
     *
     * Это отдельный «публичный» тег, НЕ тот, что владелец выдаёт доверенным
     * людям: раскрыв его в открытом каталоге, владелец разрешает присылать себе
     * заявки любому, кто знает ник. Ротация публичного тега закрывает этот канал
     * и не задевает приватные адреса.
     */
    val tagB64: String,
    val nickname: String = "",
    val issuedAtMs: Long = 0L,
    val expiresAtMs: Long = 0L,
) {
    /**
     * Каноничные байты заявки для подписи.
     *
     * В отличие от [DirectoryRecord], здесь нет поля подписи внутри payload:
     * подпись передаётся рядом, а проверяющий (и клиент, и релей) считает её над
     * ПРИНЯТЫМИ байтами, не пересобирая JSON. Эта функция нужна только
     * подписывающей стороне — но использует тот же [CanonicalJson], чтобы
     * сериализация не разъехалась при будущих правках.
     */
    fun canonicalBytes(): ByteArray =
        CanonicalJson.encodeToString(serializer(), this).toByteArray(Charsets.UTF_8)

    companion object {
        const val VERSION: Int = 1

        /** Потолок срока заявки — 90 суток, синхронно с релеем (`MAX_TTL_MS`). */
        const val MAX_TTL_MS: Long = 90L * 24 * 3600 * 1000
    }
}

/**
 * КАК контакт попал на устройство (§14.3).
 *
 * Это ровно один факт — способ первичного установления ключей. Ручная сверка
 * отпечатка живёт ОТДЕЛЬНО, в [com.aegis.core.common.model.Contact.verified]:
 * два независимых факта в одном поле сделали бы его лишённым информации (снятие
 * галочки «сверено» не смогло бы восстановить способ добавления).
 *
 * Шифрование от способа НЕ зависит: слои A и B одинаковы для всех контактов.
 * Различается только то, на чём держится уверенность «это тот человек», и UI
 * обязан показывать разницу ([describe]).
 */
@Serializable
enum class ContactTrust {
    /** Способ неизвестен (запись из очень старой сборки). */
    UNKNOWN,

    /**
     * Удалённое добавление по адресу (RCH v1): `accountId` получен вне сети,
     * подпись записи каталога и привязка `accountId ↔ ed25519` проверены. MITM
     * невозможен, ЕСЛИ полученный адрес подлинный.
     */
    REMOTE_ADDRESS,

    /** Личный обмен QR/NFC: секрет слоя A перенесён физически, вне сети. */
    IN_PERSON,
    ;

    companion object {
        /** Разбор из БД, устойчивый к неизвестным значениям (старые/новые сборки). */
        fun fromStorage(raw: String?): ContactTrust =
            entries.firstOrNull { it.name == raw?.trim()?.uppercase() } ?: UNKNOWN
    }
}
