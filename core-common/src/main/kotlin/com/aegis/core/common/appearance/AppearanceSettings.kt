package com.aegis.core.common.appearance

import kotlinx.serialization.Serializable

/**
 * Настройки оформления (§14.6). Независимые пользовательские предпочтения, не
 * входящие в сравнение пресетов безопасности (§8), поэтому хранятся отдельным
 * обёрнутым файлом (см. SecureStore) — как [com.aegis.core.common.privacy.PrivacySettings]
 * и [com.aegis.core.common.notifications.NotificationSettings].
 *
 * Здесь живут ТОЛЬКО настройки, применяемые на уровне Compose «на лету»
 * (тема и обои чата): при их смене экран просто перерисовывается, перезапуск
 * Activity не нужен.
 *
 * Язык приложения (§14.6) сюда НЕ входит: смена локали должна применяться очень
 * рано (в `attachBaseContext`, до инициализации контейнера и до готовности
 * Keystore), поэтому её тег хранится отдельно в быстром синхронном хранилище
 * (см. `LocaleManager` в модуле `:app`), а не в этом обёрнутом Keystore-файле.
 * Тема/обои — не секрет, но держим их рядом с прочими настройками для единообразия.
 */
@Serializable
data class AppearanceSettings(
    /** Режим темы: тёмная (база §13) / светлая / по системе. */
    val theme: AppThemeMode = AppThemeMode.DARK,
    /** Обои экрана переписки (§14.6). */
    val chatWallpaper: ChatWallpaper = ChatWallpaper.DEFAULT,
) {
    companion object {
        val DEFAULT: AppearanceSettings = AppearanceSettings()
    }
}

/**
 * Режим темы (§14.6, §13). База — тёмная: холодная технологичная палитра как
 * основной образ бренда. Светлая — вспомогательная; «по системе» следует за
 * ночным режимом ОС.
 */
@Serializable
enum class AppThemeMode {
    /** Следовать системному ночному режиму. */
    SYSTEM,

    /** Всегда тёмная (по умолчанию, §13). */
    DARK,

    /** Всегда светлая. */
    LIGHT,
}

/**
 * Обои экрана переписки (§14.6). Реализованы как программные фоны из токенов
 * палитры (§13), а не как растровые картинки: так нет тяжёлых ассетов, фон
 * согласован с темой (тёмной/светлой) и не тянет разрешений на хранилище.
 * Конкретная отрисовка каждого пресета — на стороне UI (`:app`).
 */
@Serializable
enum class ChatWallpaper {
    /** Однотонный фон приложения (без обоев) — как было. */
    DEFAULT,

    /** Мягкий вертикальный градиент в бирюзовом акценте бренда. */
    TEAL_GRADIENT,

    /** Приглушённый графитовый градиент (спокойнее дефолта). */
    GRAPHITE,

    /** Глубокий «полуночный» градиент с лёгким бирюзовым свечением снизу. */
    MIDNIGHT,
}

/**
 * Язык интерфейса (§14.6). Хранит BCP-47 языковой тег; пустой тег = «по системе».
 * Реальная смена локали — через `LocaleManager` (модуль `:app`), с пересозданием
 * Activity. Переведены строковые ресурсы; часть литералов в коде ещё не
 * вынесена в ресурсы (это отдельная работа по интернационализации).
 */
@Serializable
enum class AppLanguage(val tag: String) {
    /** Следовать языку системы. */
    SYSTEM(""),

    /** Русский. */
    RUSSIAN("ru"),

    /** English. */
    ENGLISH("en");

    companion object {
        /** Подбирает вариант по сохранённому тегу (пустой/неизвестный ⇒ [SYSTEM]). */
        fun fromTag(tag: String?): AppLanguage =
            entries.firstOrNull { it.tag.isNotEmpty() && tag != null && tag.startsWith(it.tag) }
                ?: SYSTEM
    }
}
