package com.aegis.core.common.model

import com.aegis.core.common.audio.VoiceWaveform
import kotlinx.serialization.Serializable

/** Тип вложения для выбора превью/иконки в UI (§14.4). */
enum class AttachmentKind { IMAGE, VIDEO, FILE }

/**
 * Метаданные ГОЛОСОВОГО сообщения (§14.4), едущие внутри [AttachmentRef].
 *
 * Зачем отдельный класс, а не значение `AUDIO` в [AttachmentKind]. Внешний JSON
 * разбирается конфигурацией `WireJson` (`ignoreUnknownKeys = true`, но БЕЗ
 * `coerceInputValues`): НОВОЕ ПОЛЕ со значением по умолчанию старый клиент
 * молча пропускает, а НОВОЕ ЗНАЧЕНИЕ ENUM уронило бы разбор всего
 * `WireContent` — и сообщение откатилось бы на «сырой текст», то есть
 * пользователь увидел бы в ленте служебный JSON. Поэтому голосовое уходит на
 * провод как `kind = FILE` + это поле: старая версия покажет обычную карточку
 * файла с кнопкой «Скачать», новая — плеер с огибающей. Обратная
 * совместимость в обе стороны, без версии протокола.
 *
 * Сам звук — такой же зашифрованный блоб, как любое вложение: каскад слоя A на
 * СЛУЧАЙНОМ 256-битном ключе ([AttachmentRef.keyB64]). Длительность и огибающая
 * лежат ВНУТРИ E2EE-конверта, поэтому релей не знает даже того, что вложение
 * голосовое (zero-trust §7.6/§10.9) — для него это неотличимый шифртекст.
 */
@Serializable
data class VoiceMeta(
    /** Длительность записи в миллисекундах (замерена отправителем). */
    val durationMs: Long,
    /**
     * Огибающая громкости: [VoiceWaveform.BUCKETS] байт 0..255 в base64
     * (75 символов). Нужна, чтобы нарисовать «полоски» до скачивания блоба —
     * иначе входящее голосовое выглядело бы пустой полосой.
     */
    val waveformB64: String = "",
    /** Версия формата метаданных (на будущее). */
    val v: Int = 1,
)

/**
 * Ссылка на зашифрованное вложение (§14.4/§10.10 v1.0 «текст + вложения»).
 *
 * Сам файл шифруется каскадом слоя A ([com.aegis.crypto.cascade.CascadeCipher]) на
 * СЛУЧАЙНОМ 256-битном ключе [keyB64] (НЕ на PSK контакта) и загружается на релей
 * как непрозрачный блоб под опаковым [objectId] (256 бит энтропии — capability, как
 * mailbox-id). Эта ссылка кладётся ВНУТРЬ сообщения и уходит обычным конвейером
 * слой A(PSK)→B(Signal)→Tor, поэтому [keyB64] и [objectId] на проводе защищены и
 * PSK, и Signal — серверу видны лишь два не связанных между собой шифртекста
 * (блоб и конверт-ссылка), без plaintext, личности и связи «кто-кому» (§7.6/§10.9).
 *
 * Хранится в зашифрованной БД (SQLCipher) как метаданные сообщения; сами байты
 * файла — отдельным BLOB в той же БД (в открытом виде на диск не попадают, §6.3).
 */
@Serializable
data class AttachmentRef(
    /** Опаковый id блоба на релее (url-safe base64 без паддинга, 256 бит). */
    val objectId: String,
    /** Случайный 256-битный ключ каскада слоя A для блоба (base64). Секрет. */
    val keyB64: String,
    /** Исходное имя файла (для показа/иконки; в сеть не влияет на адресацию). */
    val fileName: String,
    /** MIME-тип (`image/jpeg`, `video/mp4`, `application/pdf`, …). */
    val mimeType: String,
    /** Размер ИСХОДНОГО (расшифрованного) файла в байтах. */
    val sizeBytes: Long,
    /** Класс вложения для превью (картинка/видео/файл). */
    val kind: AttachmentKind,
    /**
     * Метаданные голосового сообщения или `null` для обычного вложения (§14.4).
     * Голосовое всегда приходит с `kind = FILE` — см. обоснование в [VoiceMeta].
     */
    val voice: VoiceMeta? = null,
    /** Версия формата ссылки (на будущее). */
    val v: Int = 1,
) {
    /** Записано в приложении как голосовое сообщение (а не выбрано пикером). */
    val isVoice: Boolean get() = voice != null

    /**
     * Вложение можно проиграть встроенным плеером: либо это голосовое, либо
     * пользователь приложил аудиофайл пикером (тогда огибающей нет и она
     * синтезируется из [objectId], см. [VoiceWaveform.synthetic]).
     */
    val isPlayableAudio: Boolean
        get() = isVoice || mimeType.startsWith("audio/", ignoreCase = true)
}
